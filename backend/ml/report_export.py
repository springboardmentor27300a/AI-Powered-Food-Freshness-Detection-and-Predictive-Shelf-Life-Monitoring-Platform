"""PDF and Excel exporters (Milestone 4).

Turn a persisted report document (summary + tables) into a valid .xlsx
(xlsxwriter) or .pdf (reportlab) byte stream. Values are taken verbatim from
the report document - the same data the API returns to the UI.
"""
import io
from datetime import datetime

import xlsxwriter
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle


def _fmt_ts(value):
    if isinstance(value, datetime):
        return value.strftime("%Y-%m-%d %H:%M UTC")
    return str(value) if value else "N/A"


# ---------------------------------------------------------------------------
# Excel
# ---------------------------------------------------------------------------
def export_excel(report: dict) -> bytes:
    buf = io.BytesIO()
    wb = xlsxwriter.Workbook(buf, {"in_memory": True})

    title_fmt = wb.add_format({"bold": True, "font_size": 14})
    label_fmt = wb.add_format({"bold": True, "bg_color": "#F3F4F6", "border": 1})
    value_fmt = wb.add_format({"border": 1})
    header_fmt = wb.add_format({"bold": True, "bg_color": "#111827", "font_color": "#FFFFFF", "border": 1})

    ws = wb.add_worksheet("Summary")
    ws.write(0, 0, report.get("title") or "Report", title_fmt)
    ws.write(1, 0, "Generated", label_fmt)
    ws.write(1, 1, _fmt_ts(report.get("created_at")), value_fmt)
    ws.write(2, 0, "Generated by", label_fmt)
    ws.write(2, 1, report.get("created_by_username") or "N/A", value_fmt)
    filters = report.get("filters") or {}
    ws.write(3, 0, "Filters", label_fmt)
    ws.write(3, 1, ", ".join(f"{k}={v}" for k, v in filters.items() if v) or "None", value_fmt)
    period = report.get("period") or {}
    ws.write(4, 0, "Period", label_fmt)
    ws.write(4, 1, f"{period.get('from') or 'any'} to {period.get('to') or 'any'}", value_fmt)

    row = 6
    for item in report.get("summary") or []:
        ws.write(row, 0, item.get("label"), label_fmt)
        ws.write(row, 1, str(item.get("value", "")), value_fmt)
        row += 1

    for i, table in enumerate(report.get("tables") or []):
        name = (table.get("name") or f"Table {i + 1}")[:28]
        tws = wb.add_worksheet(name)
        columns = table.get("columns") or []
        for c, col in enumerate(columns):
            tws.write(0, c, col, header_fmt)
        for r, rowvals in enumerate(table.get("rows") or [], start=1):
            for c, val in enumerate(rowvals):
                tws.write(r, c, "" if val is None else str(val), value_fmt)
        tws.set_row(0, 20)
        if columns:
            tws.freeze_panes(1, 0)

    wb.close()
    return buf.getvalue()


# ---------------------------------------------------------------------------
# PDF
# ---------------------------------------------------------------------------
def export_pdf(report: dict) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=landscape(A4),
        leftMargin=12 * mm, rightMargin=12 * mm, topMargin=14 * mm, bottomMargin=14 * mm,
        title=report.get("title") or "Report",
    )
    styles = getSampleStyleSheet()
    h1 = ParagraphStyle("H1", parent=styles["Title"], fontSize=18, spaceAfter=4)
    meta = ParagraphStyle("Meta", parent=styles["Normal"], fontSize=9, textColor=colors.grey)

    story = [
        Paragraph(report.get("title") or "Report", h1),
        Paragraph(
            f"Generated: {_fmt_ts(report.get('created_at'))} &nbsp;|&nbsp; "
            f"By: {report.get('created_by_username') or 'N/A'} &nbsp;|&nbsp; "
            f"Filters: {', '.join(f'{k}={v}' for k, v in (report.get('filters') or {}).items() if v) or 'None'}",
            meta,
        ),
        Paragraph(report.get("description") or "", meta),
        Spacer(1, 6 * mm),
    ]

    summary = report.get("summary") or []
    if summary:
        cells = [[Paragraph(f"<b>{s.get('label')}</b>", styles["Normal"]),
                  Paragraph(str(s.get("value", "")), styles["Normal"])] for s in summary]
        half = (len(cells) + 1) // 2
        left, right = cells[:half], cells[half:]
        if len(right) < len(left):
            right.append(["", ""])
        merged = [left[i] + right[i] for i in range(len(left))]
        t = Table(merged, colWidths=[85 * mm, 60 * mm, 85 * mm, 60 * mm])
        t.setStyle(TableStyle([
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#E5E7EB")),
            ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#F9FAFB")),
            ("BACKGROUND", (2, 0), (2, -1), colors.HexColor("#F9FAFB")),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("FONTSIZE", (0, 0), (-1, -1), 8),
            ("LEFTPADDING", (0, 0), (-1, -1), 4),
            ("RIGHTPADDING", (0, 0), (-1, -1), 4),
        ]))
        story += [Paragraph("<b>Key Figures</b>", styles["Heading3"]), t, Spacer(1, 6 * mm)]

    for i, table in enumerate(report.get("tables") or []):
        story.append(Paragraph(f"<b>{table.get('name') or f'Table {i + 1}'}</b>", styles["Heading3"]))
        columns = table.get("columns") or []
        rows = table.get("rows") or []
        if not rows:
            story.append(Paragraph("No records in the selected period.", styles["Normal"]))
            continue
        data = [columns] + [[("" if v is None else str(v)) for v in r] for r in rows[:300]]
        n = len(columns)
        col_w = (273 * mm) / max(n, 1)
        t = Table(data, colWidths=[col_w] * n, repeatRows=1)
        t.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#111827")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTSIZE", (0, 0), (-1, -1), 7),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("GRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#D1D5DB")),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F9FAFB")]),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LEFTPADDING", (0, 0), (-1, -1), 3),
            ("RIGHTPADDING", (0, 0), (-1, -1), 3),
        ]))
        if len(rows) > 300:
            story.append(Paragraph(f"Showing first 300 of {len(rows)} records.", meta))
        story.append(Spacer(1, 5 * mm))

    doc.build(story)
    return buf.getvalue()
