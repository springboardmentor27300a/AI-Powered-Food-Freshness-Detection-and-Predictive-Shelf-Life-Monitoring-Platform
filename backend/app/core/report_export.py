"""
PDF and Excel writers for the Report objects built in report_data.py.
Pure formatting - no database access, no calculations.
"""
import io
from typing import Any

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table as PdfTable, TableStyle
from xml.sax.saxutils import escape

from app.core.report_data import Report

DISCLAIMER = (
    "Estimates are based on heuristic image analysis and manually entered data. "
    "They are not a food-safety certification or guarantee."
)
GREEN = "166534"


# ------------------------------- Excel ------------------------------------
def _safe_cell(value: Any) -> Any:
    """Stop user-entered text such as '=SUM(...)' being run as a formula."""
    if isinstance(value, str) and value[:1] in ("=", "+", "-", "@"):
        return "'" + value
    return value


def _sheet_name(title: str, used: set) -> str:
    base = "".join(ch for ch in title if ch not in '[]:*?/\\')[:28] or "Sheet"
    name, n = base, 2
    while name in used:
        name, n = f"{base[:25]} {n}", n + 1
    used.add(name)
    return name


def build_xlsx(report: Report) -> bytes:
    wb = Workbook()
    head_font = Font(bold=True, color="FFFFFF")
    head_fill = PatternFill("solid", fgColor=GREEN)
    wrap = Alignment(wrap_text=True, vertical="top")

    ws = wb.active
    used = {"Summary"}
    ws.title = "Summary"
    ws["A1"], ws["A1"].font = report.title, Font(bold=True, size=14)
    meta = [("Generated (UTC)", report.generated_at.strftime("%Y-%m-%d %H:%M")),
            ("Generated by", report.generated_by), ("Scope", report.scope)]
    r = 3
    for k, v in meta + [("", "")] + report.summary:
        ws.cell(r, 1, _safe_cell(k)).font = Font(bold=True)
        ws.cell(r, 2, _safe_cell(v)).alignment = Alignment(horizontal="left", wrap_text=True)
        r += 1
    r += 1
    for note in report.notes + [DISCLAIMER]:
        ws.cell(r, 1, _safe_cell(note)).alignment = wrap
        ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=6)
        ws.row_dimensions[r].height = 32
        r += 1
    ws.column_dimensions["A"].width = 58
    ws.column_dimensions["B"].width = 40

    for t in report.tables:
        sh = wb.create_sheet(_sheet_name(t.title, used))
        for i, col in enumerate(t.columns, 1):
            c = sh.cell(1, i, col)
            c.font, c.fill, c.alignment = head_font, head_fill, Alignment(wrap_text=True, vertical="center")
        if not t.rows:
            sh.cell(2, 1, t.empty_message)
        for ri, row in enumerate(t.rows, 2):
            for ci, val in enumerate(row, 1):
                sh.cell(ri, ci, _safe_cell(val)).alignment = wrap
        for i, col in enumerate(t.columns, 1):
            longest = max([len(str(col))] + [len(str(rw[i - 1])) for rw in t.rows[:200]])
            sh.column_dimensions[get_column_letter(i)].width = min(max(12, longest + 2), 60)
        sh.freeze_panes = "A2"
        sh.row_dimensions[1].height = 34

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


# -------------------------------- PDF -------------------------------------
def _p(text: Any, style) -> Paragraph:
    return Paragraph(escape(str(text)), style)


def build_pdf(report: Report) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=landscape(A4), leftMargin=12 * mm, rightMargin=12 * mm,
        topMargin=12 * mm, bottomMargin=14 * mm, title=report.title, author="Food Freshness Monitoring Platform",
    )
    ss = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=ss["Title"], fontSize=18, textColor=colors.HexColor("#" + GREEN), alignment=0)
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], fontSize=12, spaceBefore=10)
    body = ParagraphStyle("b", parent=ss["BodyText"], fontSize=8.5, leading=11)
    cell = ParagraphStyle("c", parent=body, fontSize=7, leading=8.5)
    head = ParagraphStyle("hd", parent=cell, textColor=colors.white, fontName="Helvetica-Bold")
    small = ParagraphStyle("s", parent=body, fontSize=8, textColor=colors.HexColor("#4b5563"))

    story = [_p(report.title, h1),
             _p(f"Generated (UTC): {report.generated_at:%Y-%m-%d %H:%M}   |   By: {report.generated_by}", small),
             _p(f"Scope: {report.scope}", small), Spacer(1, 6)]

    if report.summary:
        story.append(_p("Summary", h2))
        t = PdfTable([[_p(k, body), _p(v, body)] for k, v in report.summary], colWidths=[110 * mm, 60 * mm])
        t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#d1d5db")),
                               ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f0fdf4")),
                               ("VALIGN", (0, 0), (-1, -1), "TOP")]))
        t.hAlign = "LEFT"
        story.append(t)

    width = doc.width
    for tb in report.tables:
        story.append(_p(tb.title, h2))
        if not tb.rows:
            story.append(_p(tb.empty_message, body))
            continue
        # Give long free-text columns more room than short numeric ones.
        weights = []
        for i, col in enumerate(tb.columns):
            cells = [len(str(r[i])) for r in tb.rows[:100]]
            longest_word = max([len(w) for w in str(col).split()] + [len(w) for r in tb.rows[:100] for w in str(r[i]).split()[:1]])
            weights.append(min(max(max(cells + [0]), longest_word + 3, 8), 38))
        total = float(sum(weights))
        widths = [width * w / total for w in weights]
        data = [[_p(c, head) for c in tb.columns]] + [[_p(v, cell) for v in r] for r in tb.rows]
        t = PdfTable(data, colWidths=widths, repeatRows=1)
        t.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#" + GREEN)),
            ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#d1d5db")),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f9fafb")]),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LEFTPADDING", (0, 0), (-1, -1), 3), ("RIGHTPADDING", (0, 0), (-1, -1), 3),
        ]))
        story.append(t)

    story.append(_p("Notes", h2))
    for n in report.notes + [DISCLAIMER]:
        story.append(_p("• " + n, body))

    def footer(canvas, d):
        canvas.saveState()
        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(colors.HexColor("#6b7280"))
        canvas.drawString(12 * mm, 7 * mm, f"{report.title} - Food Freshness Monitoring Platform")
        canvas.drawRightString(d.pagesize[0] - 12 * mm, 7 * mm, f"Page {d.page}")
        canvas.restoreState()

    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue()
